//! Interactive page (React Flow viewer) rendered from a validated graph.

use super::graph::Graph;

const TEMPLATE: &str = include_str!("viewer.html");

/// JSON safe to inline in a `<script>` block: `<` is escaped so neither
/// `</script>` nor `<!--` can appear in the output (valid JSON either way).
fn script_json(v: &impl serde::Serialize) -> String {
    serde_json::to_string(v)
        .unwrap_or_else(|_| "null".into())
        .replace('<', "\\u003c")
        .replace('\u{2028}', "\\u2028")
        .replace('\u{2029}', "\\u2029")
}

fn html_escape(s: &str) -> String {
    s.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
}

/// Language attribute: letters, digits and `-` only.
fn lang_attr(lang: &str) -> String {
    let l: String = lang
        .chars()
        .filter(|c| c.is_ascii_alphanumeric() || *c == '-')
        .take(12)
        .collect();
    if l.is_empty() {
        "en".into()
    } else {
        l
    }
}

/// Fingerprint of the compiled-in viewer (part of the hosted page ETag).
pub fn template_hash() -> &'static str {
    use sha2::{Digest, Sha256};
    static H: std::sync::OnceLock<String> = std::sync::OnceLock::new();
    H.get_or_init(|| hex::encode(&Sha256::digest(TEMPLATE.as_bytes())[..8]))
}

/// The diff to embed: only with `diff_viewer` on and within `max_diff_kb`.
/// Bigger diffs are left out and the viewer links to "Files changed".
pub fn embeddable_diff(diff: &str, diff_viewer: bool, max_diff_kb: u32) -> Option<&str> {
    (diff_viewer && !diff.is_empty() && diff.len() <= max_diff_kb as usize * 1024).then_some(diff)
}

/// "Files changed" page of a PR. Single forge-specific spot of the page.
pub fn files_url(repo: &str, pr: u64) -> String {
    format!("https://github.com/{repo}/pull/{pr}/files")
}

pub struct PageOptions<'a> {
    pub language: &'a str,
    pub repo: &'a str,
    pub pr: u64,
    /// Raw PR diff (see [`embeddable_diff`]); `None` = not embedded.
    pub diff: Option<&'a str>,
    /// Link shown instead of the diff drawer when the diff is not embedded
    /// (too large, or `diff_viewer` off).
    pub files_url: Option<&'a str>,
}

/// Render the standalone HTML page.
pub fn render(g: &Graph, o: &PageOptions) -> String {
    // The viewer ships English and French UI strings.
    let ui_lang = if o.language.to_ascii_lowercase().starts_with("fr") {
        "fr"
    } else {
        "en"
    };
    let eyebrow = if ui_lang == "fr" {
        format!("Architecture · {} #{} · générée par wshm", o.repo, o.pr)
    } else {
        format!("Architecture · {} #{} · generated by wshm", o.repo, o.pr)
    };
    let meta = serde_json::json!({
        "lang": ui_lang,
        "repo": o.repo,
        "pr": o.pr,
        "diff": o.diff.is_some(),
        "files_url": o.files_url,
        "eyebrow": eyebrow,
    });
    let title = if g.title.is_empty() {
        format!("{} #{}", o.repo, o.pr)
    } else {
        format!("{} · {} #{}", g.title, o.repo, o.pr)
    };
    // Placeholders are replaced once each, in an order where an injected
    // value can never contain a later placeholder (they are escaped JSON or
    // HTML, and `__` sequences inside them are left as data).
    TEMPLATE
        .replacen("__LANG__", &lang_attr(o.language), 1)
        .replacen("__PAGETITLE__", &html_escape(&title), 1)
        .replacen(
            "window.GRAPH = __GRAPH__; window.META = __META__; window.DIFF = __DIFF__;",
            &format!(
                "window.GRAPH = {}; window.META = {}; window.DIFF = {};",
                script_json(g),
                script_json(&meta),
                script_json(&o.diff.unwrap_or(""))
            ),
            1,
        )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn template_has_the_placeholders() {
        assert!(TEMPLATE.contains("<html lang=\"__LANG__\">"));
        assert!(TEMPLATE.contains("<title>__PAGETITLE__</title>"));
        assert!(TEMPLATE
            .contains("window.GRAPH = __GRAPH__; window.META = __META__; window.DIFF = __DIFF__;"));
    }

    #[test]
    fn values_cannot_close_the_script_block() {
        let g = Graph {
            title: "x </script><script>alert(1)</script>".into(),
            ..Default::default()
        };
        let diff = "+ let s = \"</script><!--\";\n";
        let html = render(
            &g,
            &PageOptions {
                language: "fr\"><script>",
                repo: "o/r",
                pr: 3,
                diff: Some(diff),
                files_url: None,
            },
        );
        assert_eq!(
            html.matches("</script>").count(),
            TEMPLATE.matches("</script>").count()
        );
        assert!(!html.contains("<!--\""));
        assert!(html.contains("<html lang=\"frscript\">"));
        assert!(html.contains("\"diff\":true"));
        assert!(html.contains("\"lang\":\"fr\""));
        assert!(!html.contains("__GRAPH__") && !html.contains("__DIFF__"));
        // The diff round-trips as a JSON string.
        let start = html.find("window.DIFF = ").unwrap() + "window.DIFF = ".len();
        let end = html[start..].find(";</script>").unwrap() + start;
        let back: String = serde_json::from_str(&html[start..end]).unwrap();
        assert_eq!(back, diff);
    }

    #[test]
    fn diff_is_omitted_without_diff_viewer() {
        let html = render(
            &Graph::default(),
            &PageOptions {
                language: "en",
                repo: "o/r",
                pr: 1,
                diff: None,
                files_url: Some("https://github.com/o/r/pull/1/files"),
            },
        );
        assert!(html.contains("window.DIFF = \"\";"));
        assert!(html.contains("\"diff\":false"));
        assert!(html.contains("\"files_url\":\"https://github.com/o/r/pull/1/files\""));
    }

    #[test]
    fn diff_cap() {
        let d = "x".repeat(2048);
        assert_eq!(embeddable_diff(&d, true, 2), Some(d.as_str()));
        assert_eq!(embeddable_diff(&d, true, 1), None, "over max_diff_kb");
        assert_eq!(embeddable_diff(&d, false, 10), None, "diff_viewer off");
        assert_eq!(embeddable_diff("", true, 10), None);
    }
}
